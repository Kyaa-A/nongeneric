export const RULES_BY_ID: ReadonlyMap<string, AntipatternRule> = new Map(
  ANTIPATTERN_RULES.map((rule) => [rule.id, rule])
);

export function getRule(id: string): AntipatternRule | undefined {
  return RULES_BY_ID.get(id);
}

export function filterRulesByScope(scopes?: string[]): AntipatternRule[] {
  if (!scopes || scopes.length === 0) {
    return [...ANTIPATTERN_RULES];
  }
  const normalized = new Set(scopes.map((s) => s.trim().toLowerCase()).filter(Boolean));
  return ANTIPATTERN_RULES.filter(
    (rule) =>
      normalized.has(rule.category) ||
      rule.scopes.some((scope) => normalized.has(scope.toLowerCase()))
  );
}
